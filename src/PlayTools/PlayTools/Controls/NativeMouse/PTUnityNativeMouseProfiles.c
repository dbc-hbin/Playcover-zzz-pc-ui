bool PTUnityNativeMouseHasProfileForBundle(const char *bundleIdentifier) {
    if (bundleIdentifier == NULL || bundleIdentifier[0] == '\0') {
        return false;
    }
    for (size_t index = 0; index < sizeof(kProfiles) / sizeof(kProfiles[0]); ++index) {
        if (strcmp(bundleIdentifier, kProfiles[index].bundleIdentifier) == 0) {
            return true;
        }
    }
    return false;
}

const PTUnityNativeMouseProfile *PTUnityNativeMouseFindProfile(
    const char *bundleIdentifier,
    const uint8_t unityFrameworkUuid[16]
) {
    if (bundleIdentifier == NULL || unityFrameworkUuid == NULL) {
        return NULL;
    }
    for (size_t index = 0; index < sizeof(kProfiles) / sizeof(kProfiles[0]); ++index) {
        if (strcmp(bundleIdentifier, kProfiles[index].bundleIdentifier) == 0 &&
            memcmp(unityFrameworkUuid, kProfiles[index].unityFrameworkUuid, 16) == 0) {
            return &kProfiles[index];
        }
    }
    return NULL;
}
